"""F5.3b.2: opt-in LAB controller for an owned KoboldCpp process.

This is not a Lumi runtime provider. No command is supplied or executed on
construction. The operator must supply a previously reviewed command that
starts KoboldCpp on the fixed loopback port, and a pinned /api/v1/model ID.
Never use commands generated by an LLM, user conversation or Telegram.
"""
import socket
import time
import math

from .kobold_server_canary import KoboldServerCanary, KoboldCanaryError
from .owned_process_f5 import OwnedModelProcess, OwnedProcessError


class LabServerError(RuntimeError):
    """Safe, finite error without executable path or model identifier."""


def loopback_port_free(port):
    """Best-effort port preflight, not a guarantee of future socket ownership."""
    if type(port) is not int or not 1 <= port <= 65535:
        raise LabServerError("Invalid loopback port")
    try:
        with socket.socket(socket.AF_INET, socket.SOCK_STREAM) as sock:
            sock.bind(("127.0.0.1", port))
            return True
    except OSError:
        return False


class OwnedKoboldLab:
    """One child at a time; only explicit start/stop, no inference or persistence."""

    def __init__(self, *, port=5001, process=None, canary=None,
                 port_check=None, clock=None, pause=None):
        if type(port) is not int or not 1 <= port <= 65535:
            raise LabServerError("Invalid port")
        self.port = port
        self._process = process if process is not None else OwnedModelProcess()
        self._canary = canary if canary is not None else KoboldServerCanary(
            "http://127.0.0.1:" + str(port))
        self._port_check = port_check or loopback_port_free
        self._clock = clock or time.monotonic
        self._pause = pause or time.sleep
        self._ready = False
        self._expected = None

    @property
    def ready(self):
        return self._ready and self._process.is_running()

    def start(self, command, *, expected_model, timeout=15):
        """Wait for matching model identity; on failure stop the owned child.

        A local probe cannot prove socket ownership: treat this as a lab-only
        identity test. It is NEVER sufficient to route private conversations.
        """
        if (type(expected_model) is not str or not expected_model.strip()
                or len(expected_model) > 256 or "\x00" in expected_model):
            raise LabServerError("Exact expected model ID required")
        if type(timeout) not in (int, float) or not math.isfinite(timeout) or not 0 < timeout <= 120:
            raise LabServerError("Invalid readiness timeout")
        if self._process.blocked or self._process.is_running() or self._expected is not None:
            raise LabServerError("Previous model not released")
        if not self._port_check(self.port):
            raise LabServerError("Loopback port already in use")
        try:
            pid = self._process.start(command)
        except OwnedProcessError:
            raise LabServerError("Failed to start owned process") from None
        self._expected = expected_model
        deadline = self._clock() + timeout
        try:
            while self._clock() < deadline:
                if not self._process.is_running():
                    raise LabServerError("Model process exited during startup")
                try:
                    identity = self._canary.probe()
                except KoboldCanaryError:
                    identity = None
                if identity is not None:
                    if identity != expected_model:
                        raise LabServerError("Loaded model identity mismatch")
                    # Recheck parent process before reporting readiness.
                    if not self._process.is_running():
                        raise LabServerError("Model process exited before readiness")
                    self._ready = True
                    return pid
                self._pause(0.1)
            raise LabServerError("Model did not become ready")
        except (LabServerError, KoboldCanaryError, OSError, ValueError) as exc:
            self._ready = False
            try:
                self._process.stop(timeout=10)
            except OwnedProcessError:
                # Leave blocked; do not permit a second process.
                raise LabServerError("Startup failed; release unverified") from None
            self._expected = None
            if isinstance(exc, LabServerError):
                raise
            raise LabServerError("Local model readiness check failed") from None

    def stop(self, *, timeout=10):
        self._ready = False
        try:
            self._process.stop(timeout=timeout)
        except OwnedProcessError:
            raise LabServerError("Model release unverified") from None
        self._expected = None
        return True
