"""Explicit owner-only 'leave a message for the authorized contact' intent.

This parser is called ONLY on local typed/voice input, never on incoming
Telegram messages or text generated by GPT. It does not send anything itself.
"""
from __future__ import annotations

import re


def explicit_telegram_note(message:str,contact_name:str="") -> str|None:
    if not isinstance(message,str) or not 8<=len(message)<=950:
        return None
    text=" ".join(message.strip().split())
    text=re.sub(r"^jarvis[,\s:]+","",text,flags=re.I)
    # No fuzzy matching against arbitrary names or users: the sole contact
    # has already been explicitly selected by the owner in the setup wizard.
    phrases=[r"(?:alla\s+mia\s+amica|al\s+mio\s+contatto)",
             r"(?:alla\s+mia\s+amica|al\s+mio\s+contatto)"]
    if isinstance(contact_name,str) and contact_name.strip():
        name=contact_name.strip()
        if len(name)<=90:
            phrases.append(r"(?:a|ad)\s+"+re.escape(name))
            first=name.split()[0]
            if len(first)>=3:
                phrases.append(r"(?:a|ad)\s+"+re.escape(first))
    recipient="(?:"+ "|".join(phrases)+")"
    match=re.fullmatch(
        r"(?:riferisci|di'|dì|lascia\s+detto|lascia\s+un\s+messaggio)\s+"
        +recipient+r"\s+(?:che\s+|:\s*)(.{3,700})",
        text,flags=re.I)
    if not match:
        return None
    note=match.group(1).strip(" .")
    return note if note else None
